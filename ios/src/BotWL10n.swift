/// The text for a key (the key itself if the table lacks it)
func tr(_ key: String) -> String {
    BotWL10n.table[key] ?? key
}

func tr(_ key: String, _ args: CVarArg...) -> String {
    String(format: tr(key), arguments: args)
}

/// A message kept as its key and arguments and put into words when shown, so an alert still on screen follows a language
/// switch (user 2026-11-12: "Game files imported" stayed in Chinese after switching to English). raw: text that is not
/// in the table (an error's own description)
struct BotWText {
    let key: String
    let args: [CVarArg]
    let raw: String?
    init(_ key: String, _ args: CVarArg...) { self.key = key; self.args = args; raw = nil }
    init(raw: String) { key = ""; args = []; self.raw = raw }
    var text: String { raw ?? (args.isEmpty ? tr(key) : String(format: tr(key), arguments: args)) }
}
